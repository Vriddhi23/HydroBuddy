const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const fs = require('node:fs')
const profile = path.resolve('.test-data', `peek-${Date.now()}`)
const env = { ...process.env, HYDROBUDDY_TEST_DATA: profile }
delete env.ELECTRON_RUN_AS_NODE
let app
const errors = []
async function launch() {
  app = await electron.launch({ args: [path.resolve('out/main/main.js'), '--fast-reminders'], env })
  for (let i=0;i<100&&!app.windows().some(p=>p.url().includes('/settings'));i++) await new Promise(r=>setTimeout(r,100))
  const settings=app.windows().find(p=>p.url().includes('/settings')), companion=app.windows().find(p=>p.url().includes('/companion'))
  for(const p of app.windows()) p.on('pageerror', e=>errors.push(e.message))
  await settings.waitForSelector('h1')
  return {settings,companion}
}
const phase = (p,value) => p.waitForSelector(`[data-phase="${value}"]`,{state:'attached',timeout:15000})
const shot = (p,name) => p.screenshot({path:`test-results/${name}.png`,omitBackground:true})
async function run() {
  let {settings,companion}=await launch()
  await settings.waitForSelector('dialog.avatar-chooser[open]')
  await shot(settings,'avatar-chooser')
  await settings.getByRole('button',{name:'Pick a character'}).click()
  assert.equal(await settings.locator('.avatar-chooser').count(),0)
  assert.equal(await settings.getByRole('button',{name:'Classic walk'}).count(),0)
  assert.equal(await settings.getByRole('button',{name:'Side-view walk'}).count(),0)
  await settings.getByRole('button',{name:'Male',exact:true}).click()
  await settings.getByRole('button',{name:'green clothing',exact:true}).click()
  await settings.getByRole('button',{name:'pink bottle',exact:true}).click()
  await settings.getByLabel('What should we call your buddy?').fill('Mini me')
  await settings.getByLabel('A reminder, in your words.').fill('Hey, take a sip. Your water is waiting.')
  await shot(settings,'onboarding')
  await settings.getByRole('button',{name:'Meet My HydroBuddy'}).click()
  await phase(companion,'peeking')
  await companion.waitForTimeout(850)
  assert.equal(await companion.locator('.buddy-figure').evaluate(n=>getComputedStyle(n).clipPath),'none')
  assert.equal(await companion.locator('.speech-bubble').count(),0)
  await shot(companion,'builtin-peek')
  const native=await app.evaluate(({BrowserWindow})=>{const w=BrowserWindow.getAllWindows().find(w=>w.webContents.getURL().includes('/companion'));const p=w.webContents.getLastWebPreferences();return w.isVisible()&&w.isAlwaysOnTop()&&!w.isFocusable()&&p.contextIsolation&&!p.nodeIntegration&&p.sandbox})
  assert(native)
  await phase(companion,'entering')
  const before=await companion.locator('.leg-left').evaluate(n=>getComputedStyle(n).transform)
  await companion.waitForTimeout(170)
  assert.notEqual(await companion.locator('.leg-left').evaluate(n=>getComputedStyle(n).transform),before)
  await phase(companion,'greeting')
  assert.match(await companion.locator('.speech-bubble p').innerText(),/Your water is waiting/)
  await phase(companion,'asking')
  await companion.getByRole('button',{name:'Yes 💧',exact:true}).click()
  await phase(companion,'positive'); await phase(companion,'hidden')
  await app.close(); ({settings,companion}=await launch())
  assert.equal(await settings.locator('.avatar-chooser').count(),0)
  assert.equal(await settings.getByLabel('What should we call your buddy?').inputValue(),'Mini me')
  await settings.getByRole('button',{name:'Your routine',exact:true}).click()
  await settings.getByRole('switch',{name:'Enable reminders'}).click()
  await settings.getByRole('button',{name:'Save changes',exact:true}).click()
  await settings.waitForFunction(async()=>!(await window.buddy.getState()).preferences.remindersEnabled)
  await settings.getByRole('button',{name:'Your buddy',exact:true}).click()
  await settings.getByRole('button',{name:'Change avatar'}).click()
  await settings.getByRole('button',{name:'Use my own image'}).click()
  await settings.getByRole('button',{name:'Try the supplied avatar'}).click()
  await settings.waitForSelector('[data-renderer="supplied-motion"] .supplied-avatar-art')
  assert.equal(await settings.locator('.avatar-chooser').count(),0)
  await settings.getByRole('button',{name:'Save changes',exact:true}).click()
  await settings.waitForFunction(async()=>(await window.buddy.getState()).preferences.avatar.source==='custom')
  const firstID=(await settings.evaluate(()=>window.buddy.getState())).preferences.avatar.frontAsset
  assert(fs.existsSync(path.join(profile,'avatars',firstID+'.png')))
  await shot(settings,'custom-avatar')
  await settings.getByRole('button',{name:'Test Reminder',exact:true}).click()
  await phase(companion,'peeking'); await companion.waitForTimeout(850)
  assert.equal(await companion.locator('.buddy-figure').evaluate(n=>getComputedStyle(n).clipPath),'none')
  await shot(companion,'custom-peek')
  await phase(companion,'asking'); await shot(companion,'custom-companion')
  await companion.getByRole('button',{name:'Not yet',exact:true}).click()
  await phase(companion,'negative'); await phase(companion,'hidden')
  // Real DOM drop exercises byte import through the secure preload, without a path API.
  await settings.locator('.avatar-import').evaluate((node,bytes)=>{const transfer=new DataTransfer();transfer.items.add(new File([new Uint8Array(bytes)],'avatar.png',{type:'image/png'}));node.dispatchEvent(new DragEvent('drop',{bubbles:true,dataTransfer:transfer}))},Array.from(fs.readFileSync('src/renderer/public/welcome-buddy.png')))
  await settings.waitForFunction(original=>document.querySelector('.preview-play')&&!document.querySelector('.import-front').disabled,firstID)
  await settings.getByRole('button',{name:'Save changes',exact:true}).click()
  await settings.waitForFunction(async id=>(await window.buddy.getState()).preferences.avatar.frontAsset!==id,firstID)
  await settings.waitForTimeout(100)
  assert(!fs.existsSync(path.join(profile,'avatars',firstID+'.png')))
  assert(await settings.evaluate(async()=>{try{await window.buddy.importAvatarData(new Uint8Array([1,2,3]));return false}catch{return true}}))
  assert(await settings.evaluate(async()=>{try{await window.buddy.readAvatar('../../preferences.json');return false}catch{return true}}))
  await app.close(); ({settings,companion}=await launch())
  await settings.waitForSelector('[data-renderer="custom-flat"]')
  await settings.getByRole('button',{name:'Use the original greeting'}).click()
  assert.equal(await settings.getByLabel('A reminder, in your words.').inputValue(),'Hey, it’s time to get hydrated.')
  await companion.emulateMedia({reducedMotion:'reduce'})
  await settings.getByRole('button',{name:'Test Reminder',exact:true}).click()
  await phase(companion,'asking'); await companion.getByRole('button',{name:'Dismiss reminder'}).click(); await phase(companion,'hidden')
  await settings.getByRole('button',{name:'Your routine',exact:true}).click()
  await settings.getByRole('switch',{name:'Enable reminders'}).click()
  await settings.getByRole('button',{name:'Save changes',exact:true}).click()
  await settings.evaluate(()=>window.buddy.closeSettings())
  await phase(companion,'asking'); await companion.getByRole('button',{name:'Dismiss reminder'}).click(); await phase(companion,'hidden')
  assert.deepEqual(errors,[])
  console.log('PASS: chooser, colors, face-only peek, walking limbs, supplied avatar, real image drop, validation, restart persistence, managed cleanup, both answers, reduced motion, native window security and background timer.')
}
run().catch(e=>{console.error(e);process.exitCode=1}).finally(async()=>{if(app)await app.close().catch(()=>{})})
