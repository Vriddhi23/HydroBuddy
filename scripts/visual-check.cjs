const { _electron: electron } = require('playwright')
const assert = require('node:assert/strict')
const path = require('node:path')
const env = { ...process.env, HYDROBUDDY_TEST_DATA: path.resolve('.test-data', 'visual-' + Date.now()) }
delete env.ELECTRON_RUN_AS_NODE
let app
async function run() {
  app = await electron.launch({ args: [path.resolve('out/main/main.js')], env })
  for (let i = 0; i < 100 && !app.windows().some(p => p.url().includes('/settings')); i++) await new Promise(r => setTimeout(r, 100))
  const page = app.windows().find(p => p.url().includes('/settings'))
  await page.waitForSelector('h1')
  await page.getByRole('button', { name: 'Pick a character' }).click()
  await page.getByLabel('What should we call your buddy?').fill('Mini me')
  await page.getByLabel('A reminder, in your words.').fill('Hey, take a sip. That project can wait a second.')
  await page.screenshot({ path: 'test-results/onboarding.png' })
  await page.getByRole('button', { name: 'About HydroBuddy' }).click()
  await page.waitForSelector('dialog[open]')
  await page.keyboard.press('Escape')
  assert.equal(await page.locator('dialog').count(), 0)
  await page.getByRole('button', { name: 'Change avatar' }).click()
  await page.getByRole('button', { name: 'Use my own image' }).click()
  await app.evaluate(({ dialog }, file) => { dialog.showOpenDialog = async () => ({ canceled: false, filePaths: [file] }) }, path.resolve('src/renderer/public/welcome-buddy.png'))
  await page.getByRole('button', { name: 'Choose avatar image' }).click()
  await page.waitForSelector('[data-renderer="custom-flat"]')
  const original = await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('/settings')).getSize())
  for (const [width, height, filename] of [[...original, 'custom-avatar'], [820, 700, 'compact-studio']]) {
    await app.evaluate(({ BrowserWindow }, size) => BrowserWindow.getAllWindows().find(w => w.webContents.getURL().includes('/settings')).setSize(...size), [width, height])
    await page.waitForTimeout(150)
    const bubble = await page.locator('.preview-speech').boundingBox()
    const figure = await page.locator('.figure-front').boundingBox()
    assert(bubble.y + bubble.height < figure.y, 'Speech stays clear of the avatar')
    const footer = await page.locator('.studio-footer').boundingBox()
    const viewport = await page.evaluate(() => ({ width: innerWidth, height: innerHeight, scrollWidth: document.documentElement.scrollWidth }))
    assert(footer.y + footer.height <= viewport.height + 1 && viewport.scrollWidth <= viewport.width)
    await page.screenshot({ path: 'test-results/' + filename + '.png' })
  }
  await page.getByLabel('A reminder, in your words.').fill('W'.repeat(110))
  await page.getByRole('button', { name: 'Test Reminder' }).click()
  const companion = app.windows().find(p => p.url().includes('/companion'))
  await companion.waitForSelector('[data-phase="greeting"]', { state: 'attached' })
  const bounds = await companion.locator('.speech-bubble').boundingBox()
  assert(bounds.y >= 0, 'Longest allowed greeting stays inside the desktop overlay')
  console.log('PASS: final layouts, no speech/avatar overlap at default and compact size, visible footer, keyboard modal dismissal, and long-greeting containment.')
}
run().catch(e => { console.error(e); process.exitCode = 1 }).finally(async () => { if (app) await app.close().catch(() => {}) })
